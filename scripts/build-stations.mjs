// Builds data/stations.js from supabase/seed.sql + seed-wave2.sql.
// SQL files are the source of truth; demos never hand-carry station rows.
// Run: npm --prefix scripts run build:stations   (after any seed edit)
import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function splitTuples(sql) {
  let s = sql.slice(sql.toLowerCase().indexOf("values") + 6);
  s = s.replace(/on\s+conflict[\s\S]*$/i, "").trim().replace(/;$/, "");
  const rows = [];
  let i = 0;
  while (i < s.length) {
    while (i < s.length && /[\s,]/.test(s[i])) i++;
    if (s[i] !== "(") break;
    let depth = 0, inStr = false;
    const start = i;
    while (i < s.length) {
      const c = s[i];
      if (inStr) {
        if (c === "'") { if (s[i + 1] === "'") { i += 2; continue; } inStr = false; }
        i++; continue;
      }
      if (c === "'") { inStr = true; i++; continue; }
      if (c === "(") depth++;
      if (c === ")") { depth--; if (depth === 0) { i++; break; } }
      i++;
    }
    rows.push(s.slice(start, i));
  }
  return rows;
}

function splitFields(tup) {
  const inner = tup.trim().replace(/^\(/, "").replace(/\)$/, "");
  const f = [];
  let i = 0, cur = "", depth = 0, inStr = false;
  const push = () => { f.push(cur.trim()); cur = ""; };
  while (i < inner.length) {
    const c = inner[i];
    if (inStr) {
      cur += c;
      if (c === "'") { if (inner[i + 1] === "'") { cur += inner[i + 1]; i += 2; continue; } inStr = false; }
      i++; continue;
    }
    if (c === "'") { inStr = true; cur += c; i++; continue; }
    if (c === "(") { depth++; cur += c; i++; continue; }
    if (c === ")") { depth--; cur += c; i++; continue; }
    if (c === "," && depth === 0) { push(); i++; continue; }
    cur += c; i++;
  }
  push();
  return f;
}

function unq(v) {
  v = v.trim();
  if (/^null$/i.test(v)) return null;
  if (v.startsWith("'") && v.endsWith("'")) return v.slice(1, -1).replace(/''/g, "'");
  if (v === "true") return true;
  if (v === "false") return false;
  const n = Number(v);
  return Number.isNaN(n) ? v : n;
}
function point(v) {
  const m = String(v).match(/POINT\(([-\d.]+) ([-\d.]+)\)/);
  return m ? { lng: +m[1], lat: +m[2] } : { lng: 0, lat: 0 };
}
function fuels(v) {
  const m = String(v || "").match(/\{([^}]*)\}/);
  return m ? m[1].split(",").map((x) => x.trim()).filter(Boolean) : [];
}
function availOf(v) {
  try {
    const o = JSON.parse(v);
    const vals = Object.values(o);
    if (!vals.length) return "Available";
    const s = String(vals[0]);
    return s.charAt(0).toUpperCase() + s.slice(1);
  } catch { return "Available"; }
}
const LGA_OF = { Lekki: "Eti-Osa", "Victoria Island": "Eti-Osa", Ikoyi: "Eti-Osa", Ajah: "Eti-Osa", Yaba: "Lagos Mainland", Surulere: "Surulere", Ikeja: "Ikeja" };

function parseSeed(file, cols, withGeo) {
  const sql = readFileSync(join(root, file), "utf8");
  return splitTuples(sql).map((t) => {
    const f = splitFields(t);
    const g = {};
    cols.forEach((c, i) => { g[c] = unq(f[i]); });
    const pt = point(g.location);
    const price = g.petrol_price ?? g.cng_price ?? g.ev_price ?? 0;
    return {
      name: g.name, state: g.state || "Lagos", lga: g.lga || LGA_OF[g.area] || "",
      area: g.area, addr: g.address, lng: pt.lng, lat: pt.lat,
      fuels: fuels(g.fuels), pp: price, unit: g.price_unit || "/L",
      open: g.is_open !== false, avail: availOf(g.availability),
      hours: g.hours || "Open 24 hrs", rate: g.rating ?? 4.0, rc: g.review_count ?? 0,
    };
  });
}

const C1 = ["name", "area", "address", "location", "fuels", "petrol_price", "cng_price", "ev_price", "price_unit", "price_updated_at", "is_open", "availability", "hours", "rating", "review_count"];
const C2 = ["name", "state", "lga", "lcda", "area", "address", "location", "fuels", "petrol_price", "cng_price", "ev_price", "price_unit", "price_updated_at", "is_open", "availability", "hours", "rating", "review_count"];

const rows = [
  ...parseSeed("supabase/seed.sql", C1),
  ...parseSeed("supabase/seed-wave2.sql", C2),
];
const out = "// GENERATED by scripts/build-stations.mjs from supabase/seed.sql + seed-wave2.sql — do not hand-edit.\n"
  + "// " + rows.length + " stations.\n"
  + "const TANKUP_STATIONS = "
  + JSON.stringify(rows.map((r, i) => ({ id: i + 1, ...r })))
  + ";\n";
mkdirSync(join(root, "data"), { recursive: true });
writeFileSync(join(root, "data/stations.js"), out);
console.log("Wrote data/stations.js with " + rows.length + " stations.");
